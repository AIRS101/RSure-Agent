function previewHighlights(data: unknown, record: EvidenceRecord | null, language: Language = "zh"): string[] {
  if (!isObject(data)) return [];
  const lines: string[] = [];
  const addLine = (value: unknown) => {
    if (value === undefined || value === null || value === "") return;
    const text = formatFact(value);
    if (text && !lines.includes(text)) lines.push(text);
  };
  addLine(firstValue(record?.summary, data.summary));
  addLine(firstValue(getPath(data, ["parsed_response", "reasoning_summary"]), data.rationale));
  addLine(getPath(data, ["parsed_response", "visual_evidence"]));
  addLine(getPath(data, ["parsed_response", "uncertainty"]));
  if (Array.isArray(data.ranked_votes) && isObject(data.ranked_votes[0])) {
    const top = data.ranked_votes[0];
    addLine(language === "en" ? `Leading vote: ${formatFact(top.option_label)}, score ${formatFact(top.score)}` : `最高票：${formatFact(top.option_label)}，得分 ${formatFact(top.score)}`);
  }
  return lines.slice(0, 3);
}

function citationDataLines(data: unknown, record: EvidenceRecord | null): string[] {
  if (!isObject(data)) return [];
  const lines: string[] = [];
  const push = (value: unknown) => {
    if (value === undefined || value === null || value === "") return;
    const text = formatFact(value);
    if (text && !lines.includes(text)) lines.push(text);
  };

  if (isScaleEvidence(record)) {
    if (data.distance && data.distance_unit) push(`实际距离：${formatFact(data.distance)} ${formatFact(data.distance_unit)}`);
    if (data.scale_value && data.scale_unit && data.scale_bar_pixels) {
      push(`比例尺：${formatFact(data.scale_value)} ${formatFact(data.scale_unit)} 对应 ${formatFact(data.scale_bar_pixels)} px`);
    }
    if (Array.isArray(data.point_a_px) && Array.isArray(data.point_b_px)) {
      push(`点位：A(${data.point_a_px.join(", ")}), B(${data.point_b_px.join(", ")})`);
    }
    const parsedLayout = data.parsed_layout;
    if (isObject(parsedLayout)) {
      const labels = Array.isArray(parsedLayout.labels)
        ? parsedLayout.labels
            .filter(isObject)
            .map((item) => item.label)
            .filter(Boolean)
            .join("、")
        : "";
      const scaleRegion = Array.isArray(parsedLayout.notable_regions)
        ? parsedLayout.notable_regions.find((item: unknown) => isObject(item) && item.id === "scale_bar")
        : null;
      if (labels) push(`识别点位：${labels}`);
      if (isObject(scaleRegion) && scaleRegion.text) push(`识别比例尺：${formatFact(scaleRegion.text)}`);
    }
  }

  if (isObjectEvidence(record)) {
    const parsed = data.parsed_response;
    if (isObject(parsed)) {
      push(`判断：${formatFact(parsed.answer || parsed.answer_label)}`);
      push(parsed.visual_evidence);
      push(parsed.reasoning_summary);
    }
    if (Array.isArray(data.detections)) {
      push(`检测数量：${data.detections.length}`);
      if (isObject(data.per_class_counts)) {
        push(`类别统计：${Object.entries(data.per_class_counts).map(([key, value]) => `${key} ${formatFact(value)}`).join("，")}`);
      }
    }
  }

  for (const item of previewHighlights(data, record)) push(item);
  for (const fact of factsFromData(data).slice(0, 4)) push(`${fact.label}：${fact.value}`);
  return lines.slice(0, 5);
}

