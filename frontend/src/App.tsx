function isObject(value: unknown): value is Record<string, unknown> {
  return Boolean(value) && typeof value === "object" && !Array.isArray(value);
}

function getPath(value: unknown, path: (string | number)[]): unknown {
  let current = value;
  for (const key of path) {
    if (isObject(current) && typeof key === "string") {
      current = current[key];
    } else if (Array.isArray(current) && typeof key === "number") {
      current = current[key];
    } else {
      return undefined;
    }
  }
  return current;
}

function firstValue(...values: unknown[]): unknown {
  return values.find((value) => value !== undefined && value !== null && value !== "");
}

function formatFact(value: unknown): string {
  if (typeof value === "number") {
    return Number.isInteger(value) ? `${value}` : Number(value.toPrecision(6)).toString();
  }
  if (typeof value === "boolean") return value ? "是" : "否";
  if (typeof value === "string") return value.length > 96 ? `${value.slice(0, 93)}...` : value;
  if (Array.isArray(value)) {
    const items = value.slice(0, 4).map(formatFact);
    return `[${items.join(", ")}${value.length > 4 ? ", ..." : ""}]`;
  }
  if (isObject(value)) {
    const entries = Object.entries(value).slice(0, 4).map(([key, item]) => `${key}: ${formatFact(item)}`);
    return `{${entries.join(", ")}${Object.keys(value).length > 4 ? ", ..." : ""}}`;
  }
  return String(value ?? "");
}

function addFact(facts: KeyFact[], label: string, value: unknown) {
  if (value === undefined || value === null || value === "") return;
  const text = formatFact(value);
  if (!text) return;
  if (facts.some((fact) => fact.label === label && fact.value === text)) return;
  facts.push({ label, value: text });
}

function factsFromData(data: unknown): KeyFact[] {
  if (!isObject(data)) return [];
  const facts: KeyFact[] = [];

  const candidate = firstValue(
    getPath(data, ["parsed_response", "answer_label"]),
    getPath(data, ["parsed_response", "answer"]),
    data.final_answer_label,
    data.answer_label,
    data.answer,
    data.raw_winner_label,
    getPath(data, ["matched_option", "option_label"]),
    getPath(data, ["best_option", "option_label"]),
    getPath(data, ["best_candidate", "option_label"])
  );
  const candidateText = firstValue(
    getPath(data, ["parsed_response", "answer"]),
    getPath(data, ["matched_option", "option_text"]),
    getPath(data, ["best_option", "option_text"]),
    getPath(data, ["best_candidate", "option_text"])
  );
  if (candidate) addFact(facts, "候选", candidateText ? `${formatFact(candidate)} · ${formatFact(candidateText)}` : candidate);

  addFact(
    facts,
    "置信度",
    firstValue(
      data.confidence,
      getPath(data, ["matched_option", "confidence"]),
      getPath(data, ["best_option", "probability"]),
      getPath(data, ["best_candidate", "score"]),
      getPath(data, ["parsed_response", "confidence"]),
      getPath(data, ["answer_readiness", "checks", "best_score"])
    )
  );
  addFact(facts, "操作", data.operation);

  if (data.distance && data.distance_unit) addFact(facts, "实际距离", `${formatFact(data.distance)} ${formatFact(data.distance_unit)}`);
  if (Array.isArray(data.point_a_px)) addFact(facts, "A 点像素", data.point_a_px.join(", "));
  if (Array.isArray(data.point_b_px)) addFact(facts, "B 点像素", data.point_b_px.join(", "));
  if (Array.isArray(data.scale_bar_endpoints_px)) addFact(facts, "比例尺端点", data.scale_bar_endpoints_px.join(", "));
  if (data.scale_bar_pixels) addFact(facts, "比例尺像素", data.scale_bar_pixels);

  const stat = firstValue(data.statistic, data.operation);
  const value = firstValue(data.value, data.computed_value, data.distance, getPath(data, ["answer_readiness", "checks", "margin"]));
  const unit = firstValue(data.unit, data.distance_unit, data.area_units);
  if (stat && value !== undefined && value !== null) {
    addFact(facts, "结果", `${formatFact(stat)} = ${formatFact(value)}${unit ? ` ${formatFact(unit)}` : ""}`);
  } else {
    addFact(facts, "数值", value);
  }

  const matchLabel = getPath(data, ["matched_option", "option_label"]);
  const absError = firstValue(getPath(data, ["matched_option", "absolute_error"]), getPath(data, ["matched_option", "absolute_numeric_error"]));
  if (matchLabel) {
    addFact(facts, "参考匹配", absError !== undefined ? `${formatFact(matchLabel)}，误差 ${formatFact(absError)}` : matchLabel);
  }

  if (Array.isArray(data.detections)) {
    const detections = data.detections.filter(isObject);
    const firstDetection = detections[0];
    addFact(facts, "检测数量", firstValue(data.total_instances, detections.length));
    if (isObject(data.per_class_counts)) {
      const counts = Object.entries(data.per_class_counts)
        .slice(0, 4)
        .map(([name, count]) => `${name} ${formatFact(count)}`)
        .join("，");
      addFact(facts, "类别统计", counts);
    }
    addFact(facts, "最高置信目标", firstDetection ? `${formatFact(firstDetection.class_name)} · ${formatFact(firstDetection.confidence)}` : undefined);
  }

  if (data.width && data.height) {
    const raster = [`${formatFact(data.width)} x ${formatFact(data.height)}`];
    if (data.count) raster.push(`${formatFact(data.count)} 波段`);
    if (data.crs) raster.push(`CRS ${formatFact(data.crs)}`);
    addFact(facts, "栅格", raster.join("，"));
  }
  if (Array.isArray(data.image_size)) addFact(facts, "图像尺寸", data.image_size.join(" x "));
  addFact(facts, "阈值", data.conf_threshold);
  addFact(facts, "像素距离", data.pixel_distance);
  if (data.scale_value && data.scale_unit) addFact(facts, "比例尺", `${formatFact(data.scale_value)} ${formatFact(data.scale_unit)}`);
  if (Array.isArray(data.products)) addFact(facts, "产品数", data.products.length);
  if (data.group_by) {
    const seriesCount = Array.isArray(data.series) ? `，序列 ${data.series.length}` : "";
    addFact(facts, "分组", `${formatFact(data.group_by)}${seriesCount}`);
  }
  addFact(facts, "实例数", data.total_instances);
  addFact(facts, "像元数", data.positive_pixels);
  if (data.area) addFact(facts, "面积", `${formatFact(data.area)} ${formatFact(data.area_units || "")}`.trim());
  if (isObject(data.parsed_layout)) {
    const labels = Array.isArray(data.parsed_layout.labels) ? data.parsed_layout.labels.length : 0;
    const arrows = Array.isArray(data.parsed_layout.arrows_or_flows) ? data.parsed_layout.arrows_or_flows.length : 0;
    addFact(facts, "版面要素", `标注 ${labels}，连线 ${arrows}`);
    const labelText = Array.isArray(data.parsed_layout.labels)
      ? data.parsed_layout.labels
          .filter(isObject)
          .map((item) => item.label)
          .filter(Boolean)
          .join("、")
      : "";
    addFact(facts, "识别点位", labelText);
    const scaleRegion = Array.isArray(data.parsed_layout.notable_regions)
      ? data.parsed_layout.notable_regions.find((item: unknown) => isObject(item) && item.id === "scale_bar")
      : null;
    if (isObject(scaleRegion)) addFact(facts, "比例尺文字", scaleRegion.text);
  }
  addFact(facts, "方法", data.method);
  addFact(facts, "错误", data.error);

  return facts.slice(0, 8);
}

