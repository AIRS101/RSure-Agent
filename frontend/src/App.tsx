function AnswerWithCitations({
  text,
  records,
  onSelect,
  language
}: {
  text: string;
  records: EvidenceRecord[];
  onSelect: (evidenceId: string) => void;
  language: Language;
}) {
  const copy = uiCopy[language];
  const validIds = new Set(records.map((record) => record.evidence_id).filter((id): id is string => Boolean(id)));
  const report = parseAnswerReport(text);
  if (report.conclusion || report.analysisParagraphs.length) {
    return (
      <div className="answer-report">
        {report.conclusion ? (
          <section className="answer-summary">
            <span>{language === "en" ? "Conclusion" : "结论"}</span>
            <p>
              <InlineAnswerContent text={report.conclusion} validIds={validIds} onSelect={onSelect} />
            </p>
          </section>
        ) : null}

        {report.analysisParagraphs.length ? (
            <section className="answer-analysis" aria-label={language === "en" ? "Analysis" : "分析正文"}>
              <div className="answer-analysis-heading">
                <span>{language === "en" ? "Analysis" : "分析"}</span>
                <small>{copy.clickableCitation}</small>
            </div>
            <div className="answer-analysis-copy">
              {report.analysisParagraphs.map((paragraph, index) => (
                <p key={`${paragraph}-${index}`}>
                  <InlineAnswerContent text={paragraph} validIds={validIds} onSelect={onSelect} />
                </p>
              ))}
            </div>
          </section>
        ) : null}
      </div>
    );
  }
  return (
    <div className="answer-text" aria-label={copy.rawAnswer}>
      <InlineAnswerContent text={text} validIds={validIds} onSelect={onSelect} />
    </div>
  );
}

function parseAnswerReport(text: string): { conclusion: string; analysisParagraphs: string[] } {
  const normalized = text.replace(/\r\n/g, "\n").trim();
  const conclusionMatch = normalized.match(/(?:^|\n)结论[:：]\s*([\s\S]*?)(?=\n\s*(?:\n\s*)?(?:分析|证据链)[:：]|$)/);
  const conclusion = conclusionMatch ? conclusionMatch[1].trim() : "";
  const analysisMatch = normalized.match(/(?:^|\n)分析[:：]\s*([\s\S]*?)(?=\n\s*(?:\n\s*)?证据链[:：]|$)/);
  const evidencePart = normalized.split(/证据链[:：]/)[1] || "";
  const evidenceLines = evidencePart
    .split("\n")
    .map((line) => line.trim().replace(/^[-•]\s*/, ""))
    .filter(Boolean);
  const analysisText = analysisMatch?.[1].trim() || evidenceLines.join(" ");
  const analysisParagraphs = analysisText
    .split(/\n\s*\n/)
    .map((paragraph) => paragraph.trim().replace(/^[-•]\s*/, ""))
    .filter(Boolean);
  return { conclusion, analysisParagraphs };
}

